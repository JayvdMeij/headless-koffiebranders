#!/usr/bin/env node
// Writes <publish dir>/_headers for Netlify after `nuxt generate`.
//
// Nuxt inlines critical CSS in <style> blocks. Instead of allowing
// 'unsafe-inline', we hash every inline style block in the generated HTML and
// allow exactly those hashes. The site ships no executable JavaScript, so
// script-src is 'none'.
import { createHash } from 'node:crypto'
import { readdir, readFile, writeFile } from 'node:fs/promises'
import { join, relative } from 'node:path'

const publishDir = process.argv[2] ?? '.output/public'

async function* htmlFiles(dir) {
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name)
    if (entry.isDirectory()) yield* htmlFiles(path)
    else if (entry.name.endsWith('.html')) yield path
  }
}

const styleHashes = new Set()
const problems = []

for await (const file of htmlFiles(publishDir)) {
  const html = await readFile(file, 'utf8')
  for (const [, css] of html.matchAll(/<style[^>]*>([\s\S]*?)<\/style>/g)) {
    styleHashes.add(`'sha256-${createHash('sha256').update(css, 'utf8').digest('base64')}'`)
  }
  // Guard rails: these would be blocked by the policy below
  if (/<script(?![^>]*type="application\/ld\+json")[^>]*>/.test(html)) problems.push(`${relative(publishDir, file)}: executable <script>`)
  if (/\sstyle="/.test(html)) problems.push(`${relative(publishDir, file)}: inline style attribute`)
  if (/\son[a-z]+="/.test(html)) problems.push(`${relative(publishDir, file)}: inline event handler`)
}

if (problems.length) {
  console.error(`CSP check failed:\n  ${problems.join('\n  ')}`)
  process.exit(1)
}

const csp = [
  "default-src 'none'",
  "script-src 'none'",
  `style-src 'self' ${[...styleHashes].sort().join(' ')}`,
  "img-src 'self' https://cdn.sanity.io",
  // Lets same-origin fetches (e.g. tools reading /robots.txt) work; there is no JS of our own
  "connect-src 'self'",
  "font-src 'self'",
  "form-action 'self'",
  "frame-ancestors 'none'",
  "base-uri 'none'",
  'upgrade-insecure-requests',
].join('; ')

const headers = `# Generated by scripts/security-headers.mjs. Do not edit by hand.
/*
  Content-Security-Policy: ${csp}
  Strict-Transport-Security: max-age=63072000; includeSubDomains; preload
  X-Content-Type-Options: nosniff
  X-Frame-Options: DENY
  Referrer-Policy: strict-origin-when-cross-origin
  Permissions-Policy: camera=(), microphone=(), geolocation=(), payment=(), usb=(), browsing-topics=()
  Cross-Origin-Opener-Policy: same-origin
  Cross-Origin-Resource-Policy: same-origin

# Hashed build assets (CSS, fonts) never change: cache for a year
/_nuxt/*
  Cache-Control: public, max-age=31536000, immutable
`

await writeFile(join(publishDir, '_headers'), headers)
console.log(`Wrote ${join(publishDir, '_headers')} (${styleHashes.size} style hashes)`)
